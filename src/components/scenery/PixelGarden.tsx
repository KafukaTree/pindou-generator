function Layer({ rects }: { rects: readonly PxRect[] }) {
  return (
    <g>
      {rects.map(([x, y, w, h, fill], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} fill={fill} />
      ))}
    </g>
  );
}

function GardenSvg({ rects }: { rects: readonly PxRect[] }) {
  return (
    <svg
      className="px-art absolute inset-0 h-full w-full"
      viewBox={`0 0 ${VIEW_W} ${VIEW_H}`}
      preserveAspectRatio="xMidYMax slice"
      shapeRendering="crispEdges"
      aria-hidden
    >
      <Layer rects={rects} />
    </svg>
  );
}

